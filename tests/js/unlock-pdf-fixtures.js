/**
 * Encrypted PDFs written by somebody else's implementation.
 *
 * WHY THESE ARE DATA RATHER THAN BUILT IN THE TEST
 *
 * /unlock-pdf/ can encrypt as well as decrypt - src/example.js writes a
 * genuinely locked document for the "Try an example" button - so a round trip
 * would have been easy to write and would have proved almost nothing. Both
 * halves would share a misreading of the specification, agree with each other
 * perfectly, and fail on every file in the world.
 *
 * So the fixtures below were produced by an implementation with no connection
 * to this one: pypdf 6.18.0, whose standard security handler was written from
 * the same specification by different people. If this code opens all of these
 * and gets the right text, the right permissions and the right page count out
 * of each, then it agrees with somebody else about what the format says.
 *
 * HOW TO MAKE MORE
 *
 * Every one is the same two-page document - a statement with the marker below
 * on page one - encrypted with a different scheme. The recipe is:
 *
 *   from pypdf import PdfReader, PdfWriter
 *   writer = PdfWriter(clone_from='plain.pdf')
 *   writer.encrypt(user_password='', owner_password='ownersecret',
 *                  permissions_flag=-21, algorithm='AES-128')
 *   writer.write('aes-128-blank.pdf')
 *
 * where the algorithm is one of RC4-40, RC4-128, AES-128, AES-256-R5 or
 * AES-256, and -21 is every permission bit set except printing (bit 3, worth
 * 4) and copying (bit 5, worth 16).
 *
 * The owner password is "ownersecret" on all eight, which is what makes the
 * owner-password route testable: it opens a document whose user password is
 * something else entirely.
 */

