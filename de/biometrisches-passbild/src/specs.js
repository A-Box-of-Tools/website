export const SPECS=RULES.map((rule)=>{
const cited=SOURCES[rule.id];
if(!cited)return{...rule,native:null};
const{native=null,...source}=cited;
return{...rule,native,source};
});
const BY_ID=new Map(SPECS.map((spec)=>[spec.id,spec]));
